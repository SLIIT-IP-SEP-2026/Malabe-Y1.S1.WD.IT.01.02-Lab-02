public class IT26102649Lab2Q1 {
	public static void main(String[] args){
		double perimeter,length,width;  
		perimeter = 100;
		// perimeter=length+width
		//perimeter=length+length*3/4
		length = perimeter*2/7;
		// width to length ratio:3/4
		width =length*3/4;
		//Output the results
		System.out.println("Length of the rectangle is " + length);
		System.out.println("Width of the rectangle is " + width);
	}
}